"""Regenerates openapi.json and everything under src/hushscript/generated/.

Runs only in the `regen` compose service (`just regen`).

    python scripts/generate.py [specPathOrUrl]     default: https://api.hushscript.com/openapi.json

hints.json comes from $CONFORMANCE_DIR/hints.json when set, otherwise from the conformance repo at
CONFORMANCE_REF, which must equal the tag in the compose default.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import urllib.request
from http import HTTPStatus
from pathlib import Path
from typing import Any, cast

DEFAULT_SPEC = "https://api.hushscript.com/openapi.json"
CONFORMANCE_REF = "v0.1.0"
HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")
HEADER = (
    "# Generated by scripts/generate.py from openapi.json and the conformance hints.json."
    " Do not edit.\n"
)

ROOT = Path(__file__).resolve().parent.parent
GENERATED = ROOT / "src" / "hushscript" / "generated"
BUILD = ROOT / "build" / "gen"


def _record(value: object, what: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise TypeError(f"{what} must be an object")
    return cast("dict[str, Any]", value)


def _string(value: object, what: str) -> str:
    if not isinstance(value, str) or value == "":
        raise TypeError(f"{what} must be a non-empty string")
    return value


def _integer(value: object, what: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(f"{what} must be an integer")
    return value


def _literal(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def emit_catalog(spec: object) -> str:
    catalog = _record(spec, "spec").get("x-error-catalog")
    if not isinstance(catalog, list) or not catalog:
        raise ValueError("spec has no x-error-catalog")
    seen: set[str] = set()
    lines: list[str] = []
    for index, raw in enumerate(cast("list[object]", catalog)):
        entry = _record(raw, f"x-error-catalog[{index}]")
        slug = _string(entry.get("slug"), f"x-error-catalog[{index}].slug")
        if slug in seen:
            raise ValueError(f"duplicate error slug {slug}")
        seen.add(slug)
        code = _integer(entry.get("code"), f"{slug}.code")
        status = _integer(entry.get("status"), f"{slug}.status")
        meaning = _string(entry.get("meaning"), f"{slug}.meaning")
        lines.append(
            f"    {_literal(slug)}: ErrorCatalogEntry({code}, {status}, {_literal(meaning)}),"
        )
    body = "\n".join(lines)
    return f"""{HEADER}
from dataclasses import dataclass
from typing import Final


@dataclass(frozen=True, slots=True)
class ErrorCatalogEntry:
    code: int
    status: int
    meaning: str


ERROR_CATALOG: Final[dict[str, ErrorCatalogEntry]] = {{
{body}
}}
"""


def emit_scopes(spec: object) -> str:
    paths = _record(_record(spec, "spec").get("paths"), "paths")
    entries: list[tuple[str, str]] = []
    for path, item in paths.items():
        operations = _record(item, f"paths.{path}")
        for method in HTTP_METHODS:
            operation = operations.get(method)
            if operation is None:
                continue
            scope = _record(operation, f"{method} {path}").get("x-required-scope")
            if scope is None:
                continue
            entries.append(
                (f"{method.upper()} {path}", _string(scope, f"{method} {path} x-required-scope"))
            )
    entries.sort()
    body = "\n".join(f"    {_literal(key)}: {_literal(scope)}," for key, scope in entries)
    return f"""{HEADER}
from typing import Final

OPERATION_SCOPES: Final[dict[str, str]] = {{
{body}
}}
"""


def emit_hints(hints: object) -> str:
    table = _record(hints, "hints.json")
    if not table:
        raise ValueError("hints.json is empty")
    body = "\n".join(
        f"    {_literal(slug)}: {_literal(_string(text, f'hints.{slug}'))},"
        for slug, text in table.items()
    )
    return f"""{HEADER}
from typing import Final

HINTS: Final[dict[str, str]] = {{
{body}
}}
"""


def _fetch_text(url: str) -> str:
    if not url.startswith("https://"):
        raise ValueError(f"refusing to fetch {url}")
    with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310  # https checked above
        if response.status != HTTPStatus.OK:
            raise RuntimeError(f"GET {url} answered {response.status}")
        text: str = response.read().decode("utf-8")
        return text


def _load_hints() -> object:
    directory = os.environ.get("CONFORMANCE_DIR")
    if directory:
        return json.loads((Path(directory) / "hints.json").read_text(encoding="utf-8"))
    url = (
        "https://raw.githubusercontent.com/Hushscript/hushscript-sdk-conformance/"
        f"{CONFORMANCE_REF}/hints.json"
    )
    return json.loads(_fetch_text(url))


def _load_spec_text(source: str) -> str:
    if source.startswith(("http://", "https://")):
        return _fetch_text(source)
    return Path(source).read_text(encoding="utf-8")


def declare_path_parameters(spec: dict[str, Any]) -> list[str]:
    """Adds a string path parameter wherever a path template names one the operation omits.

    openapi-python-client skips an operation whose template and parameters disagree, which left
    POST /v1/agent/accounts/{signup_id}/claim out of the client. Only the generator input is
    patched; openapi.json keeps the served bytes. Returns the operations that were patched.
    """
    patched: list[str] = []
    for path, item in _record(spec.get("paths"), "paths").items():
        operations = _record(item, f"paths.{path}")
        names = re.findall(r"\{([^}]+)\}", path)
        shared = {p.get("name") for p in operations.get("parameters", []) if p.get("in") == "path"}
        for method in HTTP_METHODS:
            operation = operations.get(method)
            if operation is None:
                continue
            operation_record = _record(operation, f"{method} {path}")
            declared = shared | {
                p.get("name")
                for p in operation_record.get("parameters", [])
                if p.get("in") == "path"
            }
            missing = [name for name in names if name not in declared]
            if not missing:
                continue
            parameters = operation_record.setdefault("parameters", [])
            parameters.extend(
                {"name": name, "in": "path", "required": True, "schema": {"type": "string"}}
                for name in missing
            )
            patched.append(f"{method.upper()} {path}")
    return patched


def _clear(directory: Path) -> None:
    # The directory can be a bind mount, so its contents go, not the directory itself.
    directory.mkdir(parents=True, exist_ok=True)
    for child in directory.iterdir():
        if child.is_dir():
            shutil.rmtree(child)
        else:
            child.unlink()


def generate(source: str = DEFAULT_SPEC) -> None:
    spec_text = _load_spec_text(source)
    spec = json.loads(spec_text)
    catalog = emit_catalog(spec)
    scopes = emit_scopes(spec)
    hints = emit_hints(_load_hints())

    # The spec's own bytes: key order and formatting survive and the regen diff stays reviewable.
    spec_path = ROOT / "openapi.json"
    spec_path.write_text(
        spec_text if spec_text.endswith("\n") else f"{spec_text}\n", encoding="utf-8"
    )

    if BUILD.exists():
        shutil.rmtree(BUILD)
    BUILD.parent.mkdir(parents=True, exist_ok=True)
    generator_spec = BUILD.parent / "openapi.generator.json"
    patched = declare_path_parameters(spec)
    for operation in patched:
        print(f"declared the missing path parameter of {operation} for the generator")
    generator_spec.write_text(json.dumps(spec), encoding="utf-8")
    subprocess.run(
        [
            "openapi-python-client",
            "generate",
            "--path",
            str(generator_spec),
            "--output-path",
            str(BUILD),
            "--meta",
            "none",
            "--config",
            str(ROOT / "scripts" / "generator-config.yml"),
            "--overwrite",
        ],
        check=True,
        cwd=ROOT,
    )
    _clear(GENERATED)
    for child in BUILD.iterdir():
        target = GENERATED / child.name
        if child.is_dir():
            shutil.copytree(child, target)
        else:
            shutil.copy2(child, target)
    shutil.rmtree(BUILD)
    generator_spec.unlink()
    (GENERATED / "catalog.py").write_text(catalog, encoding="utf-8")
    (GENERATED / "scopes.py").write_text(scopes, encoding="utf-8")
    (GENERATED / "hints.py").write_text(hints, encoding="utf-8")


if __name__ == "__main__":
    generate(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SPEC)
